import React from 'react';

export interface IconProps extends React.SVGProps<SVGSVGElement> {
  size?: number | string;
  className?: string;
  'aria-label'?: string;
}

function createIcon(displayName: string, renderPaths: () => React.ReactNode) {
  const Icon: React.FC<IconProps> = ({
    size = 24,
    className,
    'aria-label': ariaLabel,
    role,
    ...props
  }) => {
    const isAccessible = Boolean(ariaLabel);
    return (
      <svg
        viewBox="0 0 24 24"
        width={size}
        height={size}
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="square"
        strokeLinejoin="miter"
        className={className}
        aria-hidden={isAccessible ? undefined : 'true'}
        aria-label={ariaLabel}
        role={isAccessible ? (role || 'img') : role}
        {...props}
      >
        {renderPaths()}
      </svg>
    );
  };
  Icon.displayName = displayName;
  return Icon;
}

